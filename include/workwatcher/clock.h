/**
 * @file clock.h
 * @brief Источники времени: монотонные часы, настенные часы и «стабильные»
 *        настенные часы, устойчивые к ручному переводу системного времени.
 */

#ifndef WORKWATCHER_CLOCK_H
#define WORKWATCHER_CLOCK_H

/**
 * @brief Монотонное время в секундах с долями.
 *
 * Не зависит от перевода системных часов; подходит для измерения
 * длительностей.
 */
double ww_clock_monotonic_seconds(void);

/**
 * @brief Настенные часы (UNIX-время) в секундах с долями.
 */
double ww_clock_realtime_seconds(void);

/**
 * @brief Настенные часы, привязанные к монотонным.
 *
 * При инициализации фиксируется пара «настенное время + монотонное время».
 * Далее текущее значение вычисляется как зафиксированное настенное время
 * плюс прошедшее монотонное. Поэтому ручной перевод системных часов не
 * сдвигает вычисленные на его основе значения (например, время окончания
 * рабочего дня).
 */
typedef struct ww_stable_clock {
    double anchor_realtime;  /**< Настенное время в момент инициализации. */
    double anchor_monotonic; /**< Монотонное время в момент инициализации. */
} ww_stable_clock_t;

/**
 * @brief Фиксирует точку отсчёта стабильных часов «сейчас».
 * @param clock Инициализируемый объект; не NULL.
 */
void ww_stable_clock_init(ww_stable_clock_t *clock);

/**
 * @brief Текущее значение стабильных настенных часов, секунды с долями.
 * @param clock Инициализированный объект; не NULL.
 */
double ww_stable_clock_now(const ww_stable_clock_t *clock);

#endif /* WORKWATCHER_CLOCK_H */
